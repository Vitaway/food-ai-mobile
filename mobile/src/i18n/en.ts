type DeepString<T> = {
  [K in keyof T]: T[K] extends string
    ? string
    : T[K] extends readonly (infer U)[]
      ? DeepString<U>[]
      : DeepString<T[K]>;
};

export type TranslationTree = DeepString<typeof en>;
